"""Tasks: scheduled prompts that an agent (agy, Claude Code, opencode) runs instead of Hermes' paid LLM.

Each task is a Hermes cron job in no_agent mode whose script (generated under
<HERMES_HOME>/scripts/alternative-agents-tasks/, where Hermes requires cron scripts to live) runs task_run.py;
the script's output, the agent's answer, is what the job delivers. Hermes keeps the schedule, the
delivery and the job list; tasks.json only remembers which jobs are the agents', and whose.

No relative imports: hermes_mcp.py imports this module by path. Runs where Hermes' tools are
importable (the gateway, the MCP bridge).
"""

import json
import os
import re
import secrets
import threading
from pathlib import Path

PLUGIN_NAME = "alternative-agents"
HERMES_HOME = Path(os.environ.get("HERMES_HOME") or Path.home() / ".hermes")
SCRIPTS_SUBDIR = "alternative-agents-tasks"

_lock = threading.Lock()

SCRIPT_TEMPLATE = '''\
# {label} task generated by the alternative-agents plugin: Hermes' cron runs this script (no_agent), {label}
# does the work. Edit the task with /{prefix}_task in Telegram rather than by hand.
import os
import runpy
import sys
from pathlib import Path

sys.argv = ["task_run", {task!r}]
plugin = Path(os.environ.get("HERMES_HOME") or Path.home() / ".hermes") / "plugins" / {plugin!r}
runpy.run_path(str(plugin / "task_run.py"), run_name="__main__")
'''


def _registry_path():
    try:
        from plugins.plugin_storage import plugin_data_dir
        data = plugin_data_dir("alternative-agents")
    except Exception:
        data = HERMES_HOME / "plugin-data" / "alternative-agents"
        data.mkdir(parents=True, exist_ok=True)
    return data / "tasks.json"


def _load():
    try:
        return json.loads(_registry_path().read_text())
    except (OSError, ValueError):
        return {}


def _save(tasks):
    path = _registry_path()
    tmp = path.with_suffix(f".{os.getpid()}.tmp")  # the gateway and the bridges write it
    tmp.write_text(json.dumps(tasks, indent=2, ensure_ascii=False))
    tmp.replace(path)


def _cron(args):
    import tools.cronjob_tools  # noqa: F401  registers cronjob_manage
    from tools.registry import registry
    out = registry.dispatch("cronjob_manage", args)
    out = json.loads(out) if isinstance(out, str) else out
    if not out.get("success", True) or (out.get("error") and not out.get("success")):
        raise RuntimeError(out.get("error") or str(out)[:300])
    return out


def _slug(text):
    words = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:32].strip("-") or "task"
    return f"{words}-{secrets.token_hex(2)}"


def create(schedule, prompt, settings, name="", context_command=None):
    """Schedule ``prompt`` for the agent ``settings`` names (Backend.task_settings()); returns the task
    (job_id, name, schedule, next_run_at)."""
    prompt, schedule = prompt.strip(), schedule.strip()
    if not prompt or not schedule:
        raise ValueError("a schedule and a prompt are required")
    name = (name or " ".join(prompt.split())[:40]).strip()
    slug = _slug(name)
    backend = settings.get("backend") or "agy"
    task = {"backend": backend, "name": name, "prompt": prompt, "model": settings.get("model") or ""}
    if context_command:  # argv run before the agent; its output opens the prompt (task_run.py)
        task["context_command"] = [str(arg) for arg in context_command]
    script = HERMES_HOME / "scripts" / SCRIPTS_SUBDIR / f"{slug}.py"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(SCRIPT_TEMPLATE.format(task=json.dumps(task, ensure_ascii=False), plugin=PLUGIN_NAME,
                                             label=settings.get("label") or backend,
                                             prefix=settings.get("prefix") or backend))
    try:
        out = _cron({"action": "create", "name": f"{settings.get('prefix') or backend} · {name}", "schedule": schedule,
                     "script": f"{SCRIPTS_SUBDIR}/{slug}.py", "no_agent": True,
                     "deliver": f"telegram:{settings['chat_id']}"})
    except Exception:
        script.unlink(missing_ok=True)
        raise
    job = out.get("job") or out
    job_id = job.get("job_id") or out.get("job_id")
    with _lock:
        tasks = _load()
        tasks[job_id] = {"name": name, "prompt": prompt, "slug": slug, "backend": backend}
        _save(tasks)
    return {"job_id": job_id, "name": name, "schedule": job.get("schedule") or schedule,
            "next_run_at": job.get("next_run_at")}


def list_tasks(backend=None):
    """The agents' tasks (``backend``'s only, when given) still known to Hermes' cron, in creation order."""
    tasks = _load()
    jobs = {j["job_id"]: j for j in _cron({"action": "list"}).get("jobs", [])}
    out = []
    for job_id, task in tasks.items():
        job = jobs.get(job_id)
        if job is None or (backend and task.get("backend", "agy") != backend):
            continue
        out.append({"job_id": job_id, "name": task["name"], "prompt": task["prompt"],
                    "schedule": job.get("schedule"), "next_run_at": job.get("next_run_at"),
                    "last_status": job.get("last_status"), "state": job.get("state")})
    return out


def remove(job_id):
    with _lock:
        tasks = _load()
        task = tasks.pop(job_id, None)
        if task is None:
            raise KeyError(job_id)
        try:
            _cron({"action": "remove", "job_id": job_id})
        except RuntimeError:
            pass  # already gone from Hermes' side
        (HERMES_HOME / "scripts" / SCRIPTS_SUBDIR / f"{task['slug']}.py").unlink(missing_ok=True)
        _save(tasks)
    return task


def run_now(job_id):
    if job_id not in _load():
        raise KeyError(job_id)
    return _cron({"action": "run", "job_id": job_id})
