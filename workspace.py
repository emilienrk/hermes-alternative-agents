def _soul():
    body = _read(HERMES_HOME / "SOUL.md")
    return f"## Hermes' personality (SOUL.md) — adopt this tone\n{body}" if body else ""


def memory(heading="##"):
    """Hermes' memory files, as Markdown sections ("" when empty)."""
    parts = []
    for title, rel in ((f"What Hermes knows about {USER} (USER.md, entries separated by §)", "memories/USER.md"),
                       ("Hermes' memory (MEMORY.md, entries separated by §)", "memories/MEMORY.md")):
        body = _read(HERMES_HOME / rel)
        if body:
            parts.append(f"{heading} {title}\n{body}")
    return "\n\n".join(parts)


def thread_messages():
    """The user's text messages with Hermes on Telegram, oldest first: {ts, who, text}."""
    try:
        from hermes_state_registry import acquire, release_or_close
    except ImportError:
        return []
    db = acquire()
    try:
        row = next((r for r in db.list_gateway_sessions(active_only=True)
                    if r.get("session_key") == session_key()), None)
        if row is None:
            return []
        out = []
        for msg in db.get_messages(row["id"]):
            content = msg.get("content")
            if msg.get("role") not in ("user", "assistant") or not isinstance(content, str):
                continue
            text = " ".join(content.split())
            if not text:
                continue
            if len(text) > THREAD_MSG_CHARS:
                text = text[:THREAD_MSG_CHARS - 1] + "…"
            try:
                ts = float(msg.get("timestamp"))
            except (TypeError, ValueError):
                ts = 0.0
            out.append({"ts": ts, "who": USER if msg["role"] == "user" else "Hermes", "text": text})
        return out
    except Exception:
        logger.warning("agy-chat: cannot read the Hermes thread", exc_info=True)
        return []
    finally:
        release_or_close(db)


def hermes_thread(limit):
    """The user's recent Telegram messages with Hermes, one line each, oldest first."""
    return "\n".join(_thread_line(m) for m in thread_messages()[-limit:])


def _thread_line(message):
    return f"- {_hhmm(message['ts'])} {message['who']}: {message['text']}"


def _hhmm(ts):
    try:
        return datetime.fromtimestamp(float(ts)).strftime("%Y-%m-%d %H:%M") if ts else ""
    except (TypeError, ValueError, OSError):
        return ""


def hermes_skills():
    """Hermes' skills the agents may use: (name, description, skill dir), sorted by path."""
    import yaml
    root = HERMES_HOME / "skills"
    disabled = _disabled_skills()
    out = []
    for skill_md in sorted(root.glob("**/SKILL.md")):
        rel = skill_md.parent.relative_to(root)
        name = skill_md.parent.name
        if any(p.startswith(".") for p in rel.parts) or name in SKILLS_SKIPPED or name in disabled:
            continue
        try:
            head = skill_md.read_text().split("---", 2)
            meta = (yaml.safe_load(head[1]) if len(head) == 3 else {}) or {}
        except (OSError, yaml.YAMLError):
            continue
        out.append((meta.get("name") or name, " ".join(str(meta.get("description") or "").split()), skill_md.parent))
    return out


def _disabled_skills():
    try:
        from agent.skill_utils import get_disabled_skill_names
        return set(get_disabled_skill_names(platform="telegram"))
    except Exception:
        return set()


def hermes_mcp_servers(http_type=False):
    """Hermes' enabled MCP servers, in the mcpServers shape (Claude Code wants a type on URL servers)."""
    import yaml
    try:
        config = yaml.safe_load((HERMES_HOME / "config.yaml").read_text()) or {}
    except (OSError, yaml.YAMLError):
        return {}
    out = {}
    for name, spec in (config.get("mcp_servers") or {}).items():
        if not isinstance(spec, dict) or spec.get("enabled") is False:
            continue
        if spec.get("url"):
            entry = {"url": spec["url"]}
            if http_type:
                entry = {"type": "sse" if spec.get("transport") == "sse" else "http", **entry}
            if spec.get("headers"):
                entry["headers"] = dict(spec["headers"])
        elif spec.get("command"):
            entry = {"command": spec["command"], "args": list(spec.get("args") or [])}
            if spec.get("env"):
                entry["env"] = dict(spec["env"])
        else:
            continue
        out[str(name)] = entry
    return out


def _home(path):
    return str(path).replace(str(HOME), "~", 1)


def _read(path):
    try:
        return path.read_text().strip()
    except OSError:
        return ""


def _write_if_changed(path, text, mode=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text() == text:
            return
    except OSError:
        pass
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text)
    if mode is not None:
        os.chmod(tmp, mode)
    tmp.replace(path)
