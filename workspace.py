class Workspace:
    """An agent's working directory: inbox/ (the user's files), out/ (its files) and what it
    reads of Hermes."""

    def __init__(self, backend, root):
        self.backend = backend
        self.root = Path(os.path.expanduser(root))
        self.inbox = self.root / "inbox"
        self.outbox = self.root / "out"

    def prepare(self, now=None):
        """(Re)write the workspace; returns a summary for the doctor. Never raises."""
        summary = {"skills": 0, "mcp_servers": [], "rules_bytes": 0, "errors": []}
        for step in self.steps():
            try:
                step(summary, now or local_now())
            except Exception as e:
                logger.exception("agy-chat: workspace step %s failed", step.__name__)
                summary["errors"].append(f"{step.__name__}: {e}")
        return summary

    def steps(self):
        return ()

    def head(self):
        return "\n\n".join((
            HEADS[self.backend.name].format(user=USER),
            REPLY_RULES.format(user=USER, inbox=_home(self.inbox), outbox=_home(self.outbox),
                               no_questions=NO_QUESTIONS[self.backend.name])))

    def tools_section(self):
        notes = [f"- {TOOL_NOTES[t].format(chat_id=CHAT_ID, prefix=self.backend.prefix, agent=self.backend.label)}"
                 for t in TOOL_NOTES if t in cfg["bridge_tools"]]
        if cfg["share_mcp_servers"]:
            notes.append("- The MCP servers configured in Hermes: same access as Hermes.")
        return ("## Tools on top of yours (MCP server \"hermes\")\n" + "\n".join(notes)) if notes else ""

    def mcp_servers(self, http_type=False):
        """The bundled bridge and Hermes' MCP servers, as {name: launch spec}."""
        servers = {}
        if cfg["bridge_tools"]:
            servers["hermes"] = {"command": str(HERMES_PYTHON), "args": [str(BRIDGE)],
                                 "env": {"HERMES_HOME": str(HERMES_HOME), "AGY_CHAT_CHAT_ID": CHAT_ID,
                                         "AGY_CHAT_USER": USER, "AGY_CHAT_TOOLS": ",".join(cfg["bridge_tools"]),
                                         "AGY_CHAT_TASK": json.dumps(self.backend.task_settings(), ensure_ascii=False)}}
        if cfg["share_mcp_servers"]:
            for name, spec in hermes_mcp_servers(http_type).items():
                servers.setdefault(name, spec)
        return servers


class AgyWorkspace(Workspace):

    def __init__(self, backend, root):
        super().__init__(backend, root)
        self.agents_dir = self.root / ".agents"
        self.plugin = self.agents_dir / "plugins" / "hermes"
        self.rules_file = self.plugin / "rules" / "AGENTS.md"
        self.skills_index = self.plugin / "skills-index.md"
        self.mcp_config = self.plugin / "mcp_config.json"
        self.skills_json = self.agents_dir / "skills.json"

    def steps(self):
        return (self._write_plugin_shell, self._write_skills, self._write_mcp, self._write_rules)

    def first_turn_preamble(self):
        """Safety net for the first message of a conversation, should agy not load workspace rules."""
        return (f"(Context: your rules file {self.rules_file} describes this Telegram channel, your tools and "
                f"what Hermes knows about {USER}. If it isn't already in your rules, read it before answering.)")

    def _write_plugin_shell(self, summary, now):
        for d in (self.inbox, self.outbox, self.rules_file.parent):
            d.mkdir(parents=True, exist_ok=True)
        _write_if_changed(self.plugin / "plugin.json", json.dumps({"name": "hermes"}, indent=2) + "\n")

    def _write_rules(self, summary, now):
        parts = [self.head(), self.tools_section()]
        if cfg["share_skills"]:
            parts.append(SKILLS_SECTIONS["agy"].format(hermes_home=_home(HERMES_HOME), skills_index=self.skills_index))
        parts.append(f"## Now\n{now:%A %d %B %Y, %H:%M} (machine time, {now.tzname()}).")
        if MACHINE_NOTES:
            parts.append(f"## Machine\n{MACHINE_NOTES}")
        if cfg["share_soul"]:
            parts.append(_soul())
        if cfg["share_memory"]:
            parts.append(memory("##"))
        thread = hermes_thread(THREAD_MESSAGES) if cfg["share_thread"] else ""
        if thread:
            parts.append(f"## Recent Telegram thread between {USER} and Hermes (for context, don't answer it)\n"
                         + thread)
        text = "\n\n".join(p for p in parts if p) + "\n"
        _write_if_changed(self.rules_file, text)
        summary["rules_bytes"] = len(text.encode())

    def _write_skills(self, summary, now):
        by_parent, index = {}, []
        for name, desc, skill_dir in (hermes_skills() if cfg["share_skills"] else ()):
            index.append(f"- {name} — {desc} ({skill_dir / 'SKILL.md'})")
            if _PLAIN_NAME.match(skill_dir.name):
                by_parent.setdefault(str(skill_dir.parent), []).append(skill_dir.name)
        entries = [{"path": parent, "include_only": names} for parent, names in sorted(by_parent.items())]
        _write_if_changed(self.skills_json, json.dumps({"entries": entries}, indent=2) + "\n")
        _write_if_changed(self.skills_index, "# Hermes' skills\n\nRead the SKILL.md shown before acting.\n\n"
                          + "\n".join(index) + "\n")
        summary["skills"] = len(index)

    def _write_mcp(self, summary, now):
        servers = self.mcp_servers()
        text = json.dumps({"mcpServers": servers}, indent=2) + "\n"
        _write_if_changed(self.mcp_config, text, mode=0o600)  # carries the MCP servers' bearer tokens
        summary["mcp_servers"] = sorted(servers)


class ClaudeWorkspace(Workspace):

    def __init__(self, backend, root):
        super().__init__(backend, root)
        self.generated = self.root / ".hermes"
        self.system_prompt = self.generated / "system.md"
        self.mcp_config = self.generated / "mcp.json"
        self.plugin = self.generated / "plugin"
        self.skills_dir = self.plugin / "skills"

    def steps(self):
        return (self._write_plugin_shell, self._write_skills, self._write_mcp, self._write_system_prompt)

    def _write_plugin_shell(self, summary, now):
        for d in (self.inbox, self.outbox, self.skills_dir):
            d.mkdir(parents=True, exist_ok=True)
        _write_if_changed(self.plugin / ".claude-plugin" / "plugin.json",
                          json.dumps({"name": "hermes", "description": "Hermes' skills"}, indent=2) + "\n")

    def _write_system_prompt(self, summary, now):
        parts = [self.head(), CONTEXT_NOTE.format(user=USER), self.tools_section()]
        if cfg["share_skills"]:
            parts.append(SKILLS_SECTIONS["claude"].format(hermes_home=_home(HERMES_HOME)))
        if MACHINE_NOTES:
            parts.append(f"## Machine\n{MACHINE_NOTES}")
        if cfg["share_soul"]:
            parts.append(_soul())
        text = "\n\n".join(p for p in parts if p) + "\n"
        _write_if_changed(self.system_prompt, text)
        summary["rules_bytes"] = len(text.encode())

    def _write_skills(self, summary, now):
        """One link per Hermes skill in the plugin's skills/, so Claude Code loads them on demand."""
        wanted = {}
        for _name, _desc, skill_dir in (hermes_skills() if cfg["share_skills"] else ()):
            if _PLAIN_NAME.match(skill_dir.name):
                wanted.setdefault(skill_dir.name, skill_dir)
        for link in self.skills_dir.iterdir():
            if link.is_symlink() and (link.name not in wanted or Path(os.readlink(link)) != wanted[link.name]):
                link.unlink()
        for name, target in wanted.items():
            link = self.skills_dir / name
            if not link.is_symlink() and not link.exists():
                link.symlink_to(target, target_is_directory=True)
        summary["skills"] = len(wanted)

    def _write_mcp(self, summary, now):
        servers = self.mcp_servers(http_type=True)
        text = json.dumps({"mcpServers": servers}, indent=2) + "\n"
        _write_if_changed(self.mcp_config, text, mode=0o600)  # carries the MCP servers' bearer tokens
        summary["mcp_servers"] = sorted(servers)

    def turn_context(self, seen):
        """The block opening a message: the time, then what changed in Hermes' memory and thread since
        ``seen`` (None: a new conversation, which gets them all). Returns (block, new seen)."""
        now = local_now()
        parts = [f"Now: {now:%A %d %B %Y, %H:%M} (machine time, {now.tzname()})."]
        seen = seen or {}
        mem = memory("###") if cfg["share_memory"] else ""
        digest = hashlib.sha1(mem.encode()).hexdigest()[:16]
        if mem and seen.get("memory") != digest:
            parts.append(mem)
        messages = thread_messages() if cfg["share_thread"] else []
        fresh = [m for m in messages if m["ts"] > float(seen.get("thread_at") or 0)][-THREAD_MESSAGES:]
        if fresh:
            title = "Latest" if seen.get("thread_at") else "Recent"
            parts.append(f"### {title} messages between {USER} and Hermes on Telegram (don't answer them)\n"
                         + "\n".join(_thread_line(m) for m in fresh))
        block = "[Context from the plugin]\n" + "\n\n".join(parts) + "\n[End of context]"
        thread_at = max([m["ts"] for m in messages] + [float(seen.get("thread_at") or 0)])
        return block, {"memory": digest, "thread_at": thread_at}


