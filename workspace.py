"""What Hermes knows, written where each agent looks for it.

agy discovers customizations under <cwd>/.agents/. The "hermes" plugin there carries an
always-on rule regenerated before every turn (Hermes' memory and the recent Hermes thread
stay fresh in a long conversation), the MCP servers (Hermes' own plus hermes_mcp.py),
and skills.json points agy's skill discovery at Hermes' skill tree.

Claude Code runs apart from the user's own Claude Code setup (no settings, CLAUDE.md, plugins
or hooks of theirs): under <cwd>/.hermes/ it gets a system prompt file, an MCP config and a
plugin whose skills are links to Hermes' skills. Claude Code records the system prompt on a
conversation's first request and keeps it, so what changes (time, memory, Hermes' thread)
opens the message instead: turn_context().
"""

